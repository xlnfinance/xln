/** Centres of the grid cells that hold land, as `{ lon, lat }` in degrees. */
export const landCells = () =>
  LAND.flatMap(([lat, spans]) =>
    Array.from({ length: 360 / CELL }, (_, column) => -180 + CELL / 2 + column * CELL)
      .filter(lon => spans.some(([west, east]) => lon + CELL / 2 > west && lon - CELL / 2 < east))
      .map(lon => ({ lon, lat })),
  );
