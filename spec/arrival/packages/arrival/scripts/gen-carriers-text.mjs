// gen-carriers-text — inline carriers.ts's SOURCE into a string constant.
//
// The type-layer prelude needs carriers.ts as ambient TS *text* (stripped of `export`). Reading
// it at runtime via `fs.readFileSync` is fatal in the browser (Vite externalizes `node:fs`), so
// we bake the text into `src/type-layer/carriers-text.generated.ts` at build time — Node, worker,
// and browser all import the same string, no fs. carriers.ts stays the real TS module (its types
// are imported directly); this only mirrors its TEXT. Regenerate: pnpm build (runs this first).
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const srcFile = path.join(here, "..", "src", "type-layer", "carriers.ts");
const outFile = path.join(here, "..", "src", "type-layer", "carriers-text.generated.ts");

const text = readFileSync(srcFile, "utf8");
writeFileSync(
  outFile,
  "// GENERATED by scripts/gen-carriers-text.mjs — do not edit. Regenerate: pnpm build.\n" +
    "// The verbatim source of carriers.ts, baked as a string so the browser/worker prelude\n" +
    "// needs no `node:fs` (which Vite externalizes). carriers.ts stays the real types module.\n\n" +
    `export const CARRIERS_TEXT = ${JSON.stringify(text)};\n`,
);
console.log(`generated carriers-text (${text.length} chars)`);
