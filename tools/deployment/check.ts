const deploymentProgram = (): ts.Program => {
  const config = ts.readConfigFile(configPath, ts.sys.readFile);
  if (config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, '\n'));
  const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, root);
  if (parsed.errors.length) throw new Error(ts.formatDiagnostics(parsed.errors, {
    getCanonicalFileName: path => path, getCurrentDirectory: () => root, getNewLine: () => '\n',
  }));
  const program = ts.createProgram(parsed.fileNames, parsed.options);
  const options = program.getCompilerOptions();
  if (!options.strict || !options.allowJs || options.checkJs !== false || !options.noEmit) {
    throw new Error('DEPLOYMENT_TYPE_POLICY_INVALID');
  }
  return program;
};

const deploymentSources = (): string[] => deploymentProgram().getSourceFiles()
  .filter(file => !file.isDeclarationFile && !file.fileName.includes('/node_modules/') && /\.(?:ts|cjs|mjs|js)$/.test(file.fileName))
  .map(file => relative(root, file.fileName)).sort();

const emittedImports = (source: ts.SourceFile, options: ts.CompilerOptions): string[] => {
  const emitted = ts.transpileModule(source.text, { fileName: source.fileName,
    compilerOptions: { ...options, noEmit: false, allowImportingTsExtensions: false } }).outputText;
  const code = ts.createSourceFile(source.fileName, emitted, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  const imports: string[] = [];
  const visit = (node: ts.Node): void => {
    if ((ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) && node.moduleSpecifier
      && ts.isStringLiteralLike(node.moduleSpecifier)) imports.push(node.moduleSpecifier.text);
    if (ts.isCallExpression(node)) {
      const callee = node.expression;
      const loader = callee.kind === ts.SyntaxKind.ImportKeyword || (ts.isIdentifier(callee) && callee.text === 'require')
        || (ts.isCallExpression(callee) && ts.isIdentifier(callee.expression) && callee.expression.text === 'createRequire');
      const argument = node.arguments[0];
      if (loader && argument && ts.isStringLiteralLike(argument)) imports.push(argument.text);
    }
    ts.forEachChild(node, visit);
  };
  visit(code);
  return imports;
};

const deploymentLintScope = () => {
  const program = deploymentProgram();
  const options = program.getCompilerOptions();
  const pending = [...program.getRootFileNames()];
  const visited = new Set<string>();
  const generated: string[] = [];
  const files: string[] = [];
  for (const path of pending) {
    if (visited.has(path) || path.includes('/node_modules/') || /\.d\.[cm]?ts$/.test(path)
      || !/\.(?:ts|cjs|mjs|js)$/.test(path)) continue;
    visited.add(path);
    const source = program.getSourceFile(path) ?? ts.createSourceFile(path, readFileSync(path, 'utf8'), ts.ScriptTarget.Latest, true);
    const name = relative(root, path);
    if (name.startsWith('jurisdictions/typechain-types/')) {
      if (!source.text.startsWith('/* Autogenerated file. Do not edit manually. */')) throw new Error(`DEPLOYMENT_GENERATED_SOURCE_INVALID:${name}`);
      generated.push(name);
    } else files.push(name);
    for (const specifier of emittedImports(source, options)) {
      const resolved = ts.resolveModuleName(specifier, path, options, ts.sys).resolvedModule;
      if (!resolved && specifier.startsWith('.')) throw new Error(`DEPLOYMENT_LINT_IMPORT_UNRESOLVED:${name}:${specifier}`);
      if (resolved) pending.push(resolve(resolved.resolvedFileName));
    }
  }
  return { files: files.sort(), generated: generated.sort() };
};

const lintDeployment = async (): Promise<void> => {
  const { files, generated } = deploymentLintScope();
  const cjs = files.filter(file => file.endsWith('.cjs'));
  if (!cjs.includes('jurisdictions/scripts/foundation-hanko.cjs') || cjs.length < 3) {
    throw new Error('DEPLOYMENT_CJS_LINT_SCOPE_INCOMPLETE');
  }
  const globals = Object.fromEntries(['require', 'module', 'exports', '__dirname', '__filename', 'process',
    'Buffer', 'console', 'URL', 'fetch', 'AbortSignal', 'setTimeout', 'clearTimeout', 'setImmediate',
    'clearImmediate', 'setInterval', 'clearInterval', 'TextEncoder', 'TextDecoder', 'structuredClone', 'Bun']
    .map(name => [name, 'readonly' as const]));
  const eslint = new ESLint({ cwd: root, overrideConfig: [{
    files: ['**/*.cjs'], languageOptions: { sourceType: 'commonjs', globals },
    rules: { 'no-undef': 'error', 'no-unused-vars': ['error', { args: 'none', varsIgnorePattern: '^_' }],
      'no-eval': 'error', 'no-implied-eval': 'error', 'no-new-func': 'error', 'no-empty': 'error',
      'no-unreachable': 'error', 'no-unsafe-finally': 'error', 'valid-typeof': 'error',
      'no-loss-of-precision': 'error', 'no-dupe-args': 'error', 'no-dupe-keys': 'error' },
  }] });
  const results = await eslint.lintFiles(files);
  try {
    const debt = assertEslintDebt(results, files, root);
    console.log(`DEPLOYMENT_LINT_SCOPE:${safeStringify({ files, generated, approvedDebtRows: debt.debtRows })}`);
    console.log(`DEPLOYMENT_LINT_OK files=${files.length} cjs=${cjs.length} debt=${debt.debtRows.length}/${debt.debtHash} ` +
      `canonicalDebt=${debt.approvedDebtCount}/${debt.approvedDebtHash}; CJS inferred and linted, checkJs=false`);
  } catch (error) {
    const formatter = await eslint.loadFormatter('stylish');
    process.stdout.write(await formatter.format(results));
    throw error;
  }
};

