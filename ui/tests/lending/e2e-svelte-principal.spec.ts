import { expect, test } from '@playwright/test';
import { accountMoney } from '../svelte-wallet';
import { setBankPolicy } from './bank-policy';


test('Svelte signed savings and loan preserve exact money without leaving /app', { tag: '@functional' }, async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env['SVELTE_E2E_BASE_URL'] ?? 'http://localhost:8081/app');
  await page.getByRole('button', { name: 'Open test wallet', exact: true }).click();
  await expect(page.getByTestId('context-current')).toBeVisible();
  await page.getByRole('button', { name: 'Accounts', exact: true }).click();
  await page.getByTestId('hub-discovery-card').filter({ hasText: 'H1' }).getByTestId('hub-connect-button').click();
  await expect(page.getByTestId('account-preview').first()).toBeVisible();
  await page.getByRole('button', { name: 'Faucet', exact: true }).first().click();
  await expect.poll(async () => (await accountMoney(page)).owned).toBe(100_000_000n);
  const ids = await accountMoney(page);
  await setBankPolicy(page, ids, { termId: '1d', savingsInterestBps: 100, loanInterestBps: 100, maxPrincipal: 2_000_000n });
  await page.getByRole('button', { name: 'Lending', exact: true }).click();
  const panel = page.getByTestId('lending-panel');
  await panel.getByLabel('Term', { exact: true }).selectOption('1d');
  await panel.getByLabel('Amount', { exact: true }).fill('5');
  const riskConsent = panel.getByRole('button', { name: 'Authorize this maximum risk', exact: true });
  if (await riskConsent.isVisible()) await riskConsent.click();
  await expect(page.getByTestId('lending-offer-submit')).toBeEnabled();
  await page.getByTestId('lending-offer-submit').click();
  await expect.poll(async () => (await accountMoney(page)).owned).toBe(95_000_000n);
  await expect(panel.getByText(/5 USDC · open/)).toBeVisible();
  await panel.getByLabel('Action', { exact: true }).selectOption('borrow');
  await panel.getByLabel('Amount', { exact: true }).fill('2');
  await panel.getByLabel('Maximum rate (basis points)', { exact: true }).fill('100');
  const capacityConsent = panel.getByRole('button', { name: /^Accept as credit:/ });
  if (await capacityConsent.isVisible()) await capacityConsent.click();
  await expect(page.getByTestId('lending-borrow-submit')).toBeEnabled();
  await page.getByTestId('lending-borrow-submit').click();
  await expect.poll(async () => (await accountMoney(page)).owned).toBe(97_000_000n);
  await expect(page.getByTestId('lending-repay-submit')).toBeEnabled();
  await page.getByTestId('lending-repay-amount').fill('1');
  await page.getByTestId('lending-repay-submit').click();
  await expect.poll(async () => (await accountMoney(page)).owned).toBe(96_000_000n);
  await expect(page.getByTestId('lending-loan-row')).toContainText('active');
  await expect(page.getByTestId('lending-repay-amount')).toHaveValue('');
  await page.getByTestId('lending-repay-submit').click();
  await expect(page.getByTestId('lending-loan-row')).toContainText('repaid');
  const repaid = await accountMoney(page);
  const response = await page.request.get('/api/lending/state', { params: { hubEntityId: ids.hubId, userEntityId: ids.ownerId, tokenId: '1' } });
  expect(response.ok()).toBe(true);
  const state = await response.json();
  expect(state.loans).toHaveLength(1);
  expect(state.loans[0].repaidAmount).toMatch(/^[0-9]+$/);
  expect(repaid.owned).toBe(97_000_000n - BigInt(state.loans[0].repaidAmount));
  await panel.getByRole('button', { name: 'Withdraw', exact: true }).click();
  await expect.poll(async () => (await accountMoney(page)).owned).toBe(repaid.owned + 5_000_000n);
  await expect(panel.getByText(/closed · withdrawal/)).toBeVisible();
  await page.reload();
  await expect(page.getByTestId('context-current')).toHaveAttribute('data-entity-id', ids.ownerId);
  await expect.poll(async () => (await accountMoney(page)).owned).toBe(repaid.owned + 5_000_000n);
  await page.getByRole('button', { name: 'Lending', exact: true }).click();
  await expect(page.getByTestId('lending-loan-row')).toContainText('repaid');
  await expect(page).toHaveURL(/\/app#accounts\/lending$/);
  expect(errors).toEqual([]);
});
